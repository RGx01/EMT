#!/usr/bin/env python3
"""
Generate `store_types.py` — the ReadStore / WriteStore split — from the classifier.

WHY GENERATED
    The split is 102 read methods against 93 write methods across a 7,329-line
    class. Hand-maintaining two type surfaces against that is a drift machine:
    the first method added to `BlockStore` and forgotten here would silently be
    unavailable to every read path, and the obvious fix would be to reach for the
    writer. So the surfaces are generated from
    `.build/store_split_baseline.json`, the output is COMMITTED (reviewable,
    greppable, no import-time magic), and a test regenerates it and fails on any
    difference.

HOW THE READ TYPE WORKS
    `ReadStore` does not forward to a BlockStore — it BINDS BlockStore's own
    function objects as its own methods:

        class ReadStore:
            get_meta = _BS.get_meta

    That gives identical behaviour and exact signatures with no wrapper layer,
    and — the point of A §3.2 — the write names are simply absent. Calling
    `store().set_meta(...)` is an AttributeError at the call site, not a silent
    cross-thread write months later.

    There is no `__getattr__`. A catch-all forwarder would re-create every
    attribute it was meant to remove.

DEFENCE IN DEPTH
    `ReadStore` opens its connection with `query_only=ON`, so even a method
    reached some other way cannot write. The type stops it at the call site; the
    connection stops it at SQLite. v4 had only the second, which is why the wrong
    path was reachable at all.

    NOTE what is deliberately NOT here: v4's `_get_read_store()` falls back to the
    shared writer handle when the database is in-memory or missing
    ("correctness over the concurrency win"), which means the safe call can hand
    back the unsafe object. `ReadStore` has no fallback. §7 question 2 is what
    makes that affordable.

USAGE
    python3 .build/gen_store_types.py            # write store_types.py
    python3 .build/gen_store_types.py --check    # fail if it is out of date
"""
import argparse
import ast
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASELINE = os.path.join(ROOT, ".build", "store_split_baseline.json")
OUT = os.path.join(ROOT, "store_types.py")

HEADER = '''"""
store_types.py — the read/write store split (workstream A §3.1–§3.3).

GENERATED by .build/gen_store_types.py from .build/store_split_baseline.json.
DO NOT EDIT: regenerate instead. tests/test_store_types.py fails if this file and
the classifier disagree.

    store()   -> ReadStore   per-thread, read-only, the default
    writer()  -> WriteStore  engine thread only, raises elsewhere

`ReadStore` binds BlockStore's read methods directly and simply does not define
the write ones, so a read path cannot write: the attribute is absent. It opens
`query_only=ON` as well, so the connection refuses a write even if a method were
reached another way.
"""
from block_store import BlockStore as _BS

__all__ = ["ReadStore", "WriteStore"]


class ReadStore:
    """%d read-only methods of BlockStore, and nothing else.

    No `__getattr__`: a catch-all would restore every attribute this type exists
    to remove. No fallback to a writable store either — see the generator's
    docstring for why v4's had one and why this must not.
    """

    # No __slots__. It saves nothing that matters here (a handful of instances)
    # and it BLOCKS instance monkeypatching, which the suite relies on to stub a
    # store method for one test. A boundary that makes the tests harder to write
    # buys less than it costs; the boundary that matters is the absent write
    # methods, and __slots__ does nothing for that.

    def __init__(self, db_path: str):
        import sqlite3
        self._path = db_path
        self._read_only = True
        self._conn = sqlite3.connect(db_path, uri=db_path.startswith("file:"),
                                     isolation_level=None)
        self._conn.row_factory = sqlite3.Row
        self._conn.execute("PRAGMA busy_timeout=5000")
        self._conn.execute("PRAGMA query_only=ON")

    # `isolation_level=None` states A §7.1's per-request freshness explicitly. Be
    # accurate about what it does: Python's sqlite3 does NOT begin a transaction
    # for a SELECT under either setting — measured, `in_transaction` is False
    # after a read both ways — so the snapshot-pinning §7.1 warns about is not
    # reachable from here today. This is a statement of intent and a guard for
    # the day something issues an explicit BEGIN, not the mechanism.
    #
    # It was briefly claimed here as the fix for a real read-after-write failure
    # seen during the surfaces port. That was wrong: the failure was a test
    # fixture binding the wrong store. Corrected rather than deleted, because
    # "this line is load-bearing" is exactly the kind of claim that gets believed.

    def close(self):
        try:
            self._conn.close()
        except Exception:
            pass

    # ── bound read methods ──────────────────────────────────────────────────
'''

FOOTER = '''

class WriteStore(_BS):
    """The full store: every read method, plus the %d writers.

    Not a sibling of `ReadStore` but a superset of it — measured, 40 of the 93
    write methods (43%%) need read access, either running their own SELECT or
    calling a read method. Splitting them would put a read-then-write across two
    connections and lose the consistency v4 gets for free.

    Thread affinity is enforced by the `writer()` accessor rather than here, so
    that constructing one in a test does not need the engine loop.
    """
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    with open(BASELINE, encoding="utf-8") as fh:
        base = json.load(fh)

    tree = ast.parse(open(os.path.join(ROOT, "block_store.py"), encoding="utf-8").read())
    cls = next(n for n in tree.body
               if isinstance(n, ast.ClassDef) and n.name == "BlockStore")
    defined = {m.name for m in cls.body
               if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))}

    # The read surface, plus any no-SQL helper a read method calls (those are
    # private and never appear in a route, but the bound bodies need them).
    reads = [m for m in base["read"] if m in defined]
    helpers = [m for m in base["no_sql"]
               if m in defined and m not in ("close", "backup")]
    surface = sorted(set(reads) | set(helpers))

    # staticmethods must be re-wrapped. `_BS._finalised_clause` on a staticmethod
    # yields the PLAIN function; assigning that as a class attribute makes it an
    # instance method again, so every argument shifts by one and `self` arrives
    # where the first parameter should be. It surfaced as
    # `no such column: False.is_provisional` — a boolean formatted into SQL where
    # a table alias belonged. Silent, and nothing about the binding line says so.
    statics = {m.name for m in cls.body
               if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))
               and any(isinstance(d, ast.Name) and d.id == "staticmethod"
                       for d in m.decorator_list)}

    # Class-level CONSTANTS come across too. They are not methods, so the
    # classifier never sees them and the first run omitted all nine — which
    # surfaced as `'ReadStore' object has no attribute 'AUTO_CORRECTION_REASONS'`
    # from a route that was reading a SQL fragment off the class. Constants carry
    # no write capability, so there is nothing to withhold.
    consts = []
    for m in cls.body:
        if isinstance(m, ast.Assign):
            consts += [x.id for x in m.targets if isinstance(x, ast.Name)]
        elif isinstance(m, ast.AnnAssign) and isinstance(m.target, ast.Name):
            consts.append(m.target.id)
    consts = sorted(set(consts))

    lines = [HEADER % len(reads)]
    for name in consts:
        lines.append("    %s = _BS.%s\n" % (name, name))
    if consts:
        lines.append("\n")
    for name in surface:
        if name in statics:
            lines.append("    %s = staticmethod(_BS.%s)\n" % (name, name))
        else:
            lines.append("    %s = _BS.%s\n" % (name, name))
    lines.append(FOOTER % len(base["write"]))
    text = "".join(lines)

    if a.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("FAIL: store_types.py is out of date — run "
                  ".build/gen_store_types.py")
            return 1
        print("OK: store_types.py matches the classifier.")
        return 0

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s: %d read methods (+%d private helpers, %d constants), "
          "%d writers on WriteStore"
          % (os.path.relpath(OUT, ROOT), len(reads), len(helpers), len(consts),
             len(base["write"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
